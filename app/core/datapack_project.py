"""数据包「创作」层：命名空间 / 函数 / 进度 / 战利品表 / 函数标签。

`app/core/datapack.py` 负责「把一批命令导出成数据包」（一次性导出），
这一层负责「把数据包当成一个可反复编辑的工程」：

* 多命名空间；
* 函数（含子目录）、进度、战利品表、函数标签（`minecraft:load` /
  `minecraft:tick`）；
* 目录名兼容：1.21 用 `function` / `advancement` / `loot_table` /
  `tags/function`，更早的版本用 `functions` / `advancements` /
  `loot_tables` / `tags/functions` —— 读取时**两种都认**，写入时按
  `layout` 决定（默认 1.21+ 的单数形式）；
* 落盘仍然走「临时文件 + os.replace」原子替换。

不依赖 Qt。
"""
from __future__ import annotations

import json
import os
import re
import shutil
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable

from app.core.datapack import PACK_FORMAT

#: 1.21.1 → 48；1.21 → 48；1.20.6 → 41；1.20.4 → 26
PACK_FORMATS = {
    "1.21.1": 48, "1.21": 48, "1.20.6": 41, "1.20.5": 41, "1.20.4": 26,
    "1.20.2": 18, "1.20.1": 15, "1.19.4": 12, "1.18.2": 9,
}

#: 目录布局：单数（1.21+） / 复数（1.20-）
LAYOUT_SINGULAR = "singular"
LAYOUT_PLURAL = "plural"

#: 资源类型 → (单数目录, 复数目录, 文件后缀)
ASSET_KINDS: dict[str, tuple[str, str, str]] = {
    "function": ("function", "functions", ".mcfunction"),
    "advancement": ("advancement", "advancements", ".json"),
    "loot_table": ("loot_table", "loot_tables", ".json"),
    "predicate": ("predicate", "predicates", ".json"),
    "tag/function": ("tags/function", "tags/functions", ".json"),
}

#: 函数标签里常用的两个
COMMON_TAGS = ("minecraft:load", "minecraft:tick")

#: 合法的命名空间（与官方规则一致：小写字母 / 数字 / _ / - / .）
_NAMESPACE_RE = re.compile(r"^[a-z0-9_.\-]+$")


def _safe_path(name: str) -> str:
    """把用户输入的名字规范化成数据包内的相对路径（不带后缀）。"""
    text = str(name or "").strip().replace("\\", "/").lstrip("/")
    text = re.sub(r"\.(mcfunction|json)$", "", text, flags=re.IGNORECASE)
    parts = [re.sub(r"[^A-Za-z0-9_.\-]+", "_", part) for part in text.split("/")]
    return "/".join(part for part in parts if part) or "main"


def _atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temp_name = tempfile.mkstemp(
        prefix=path.name + ".", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as sink:
            sink.write(text)
            sink.flush()
            os.fsync(sink.fileno())
        os.replace(temp_name, path)
    except Exception:
        try:
            os.unlink(temp_name)
        except OSError:                                 # pragma: no cover
            pass
        raise


@dataclass
class PackAsset:
    """数据包里的一个资源文件。"""

    kind: str                     # function / advancement / loot_table / …
    name: str                     # 相对路径（不带后缀），例如 `shop/buy`
    text: str = ""
    namespace: str = "mcstudio"
    path: Path | None = None
    dirty: bool = False

    @property
    def suffix(self) -> str:
        return ASSET_KINDS.get(self.kind, ("", "", ".json"))[2]

    @property
    def display(self) -> str:
        return f"{self.kind.split('/')[-1]}:{self.name}{self.suffix}"

    def line_count(self) -> int:
        """有意义的内容行数（函数会跳过注释与空行）。"""
        if self.kind == "function":
            return len(self.commands())
        return len([line for line in self.text.splitlines() if line.strip()])

    def raw_line_count(self) -> int:
        """包含注释与空行的总行数。"""
        return len(self.text.splitlines())

    def to_json(self) -> dict:
        if self.suffix != ".json":
            return {}
        try:
            payload = json.loads(self.text or "{}")
        except ValueError:
            return {}
        return payload if isinstance(payload, dict) else {}

    def set_json(self, payload: dict) -> None:
        self.text = json.dumps(payload, ensure_ascii=False, indent=2)
        self.dirty = True

    def commands(self) -> list[str]:
        if self.kind != "function":
            return []
        return [line.strip().lstrip("/") for line in self.text.splitlines()
                if line.strip() and not line.strip().startswith("#")]

    def summary(self) -> str:
        if self.kind == "function":
            return f"{self.line_count()} 行命令"
        try:
            payload = self.to_json()
        except Exception:                               # pragma: no cover
            return "无法解析的 JSON"
        return f"{len(payload)} 个顶层字段"


@dataclass
class AuthoringPack:
    """一个可反复编辑的数据包工程。"""

    root: Path
    namespace: str = "mcstudio"
    description: str = "Generated by MCStudio"
    layout: str = LAYOUT_SINGULAR
    pack_format: int = PACK_FORMAT
    assets: list[PackAsset] = field(default_factory=list)
    tags: dict[str, list[str]] = field(default_factory=dict)

    def __post_init__(self) -> None:
        # 允许调用方直接传字符串路径（GUI / CLI 都方便）
        self.root = Path(self.root)
        self.namespace = str(self.namespace or "mcstudio").strip().lower()
        if self.layout not in (LAYOUT_SINGULAR, LAYOUT_PLURAL):
            self.layout = LAYOUT_SINGULAR

    # ---- 目录 ----

    def data_dir(self) -> Path:
        return self.root / "data" / self.namespace

    def asset_dir(self, kind: str) -> Path:
        singular, plural, _suffix = ASSET_KINDS.get(kind, (kind, kind, ".json"))
        name = singular if self.layout == LAYOUT_SINGULAR else plural
        return self.data_dir() / name

    def pack_mcmeta_path(self) -> Path:
        return self.root / "pack.mcmeta"

    def summary(self) -> str:
        kinds: dict[str, int] = {}
        for asset in self.assets:
            kinds[asset.kind] = kinds.get(asset.kind, 0) + 1
        detail = "、".join(f"{key} {value}"
                          for key, value in sorted(kinds.items())) or "空"
        return (f"命名空间 {self.namespace} · {len(self.assets)} 个资源"
                f"（{detail}）· 函数标签 {len(self.tags)} 个"
                f" · pack_format {self.pack_format}")

    # ---- 资源管理 ----

    def find(self, kind: str, name: str) -> PackAsset | None:
        clean = _safe_path(name)
        for asset in self.assets:
            if asset.kind == kind and asset.name == clean:
                return asset
        return None

    def add_asset(self, kind: str, name: str, text: str = "") -> PackAsset:
        clean = _safe_path(name)
        existing = self.find(kind, clean)
        if existing is not None:
            if text:
                existing.text = text
                existing.dirty = True
            return existing
        asset = PackAsset(kind=kind, name=clean, text=text,
                          namespace=self.namespace)
        self.assets.append(asset)
        return asset

    def remove_asset(self, kind: str, name: str) -> bool:
        clean = _safe_path(name)
        before = len(self.assets)
        self.assets = [asset for asset in self.assets
                       if not (asset.kind == kind and asset.name == clean)]
        return len(self.assets) != before

    def by_kind(self, kind: str) -> list[PackAsset]:
        return sorted((asset for asset in self.assets if asset.kind == kind),
                      key=lambda asset: asset.name)

    def set_tag(self, tag: str, entries: Iterable[str]) -> None:
        key = str(tag or "").strip()
        if not key:
            return
        if not key.startswith("#"):
            key = key if ":" in key else f"{self.namespace}:{key}"
        self.tags[key] = [str(item) for item in entries]

    def tag_entries(self, tag: str) -> list[str]:
        return list(self.tags.get(tag, []))

    # ---- 读写 ----

    def pack_mcmeta_text(self) -> str:
        return json.dumps(
            {"pack": {"pack_format": int(self.pack_format),
                      "description": self.description}},
            ensure_ascii=False, indent=2) + "\n"

    def save(self, *, changed_only: bool = False) -> list[Path]:
        """落盘：pack.mcmeta + 所有资源 + 函数标签（原子替换）。"""
        written: list[Path] = []
        self.root.mkdir(parents=True, exist_ok=True)
        _atomic_write_text(self.pack_mcmeta_path(), self.pack_mcmeta_text())
        written.append(self.pack_mcmeta_path())

        for asset in self.assets:
            if changed_only and not asset.dirty and asset.path is not None:
                continue
            path = self.asset_path(asset)
            for other in {ASSET_KINDS.get(asset.kind, ("", "", ""))[0],
                          ASSET_KINDS.get(asset.kind, ("", "", ""))[1]}:
                if not other:                           # pragma: no cover
                    continue
                old = self.data_dir() / other / f"{asset.name}{asset.suffix}"
                if old != path and old.exists():
                    try:
                        old.unlink()
                    except OSError:                     # pragma: no cover
                        pass
            _atomic_write_text(path, self._asset_text(asset))
            asset.path = path
            asset.dirty = False
            written.append(path)

        for tag, entries in self.tags.items():
            path = self.tag_path(tag)
            payload = {"values": list(entries)}
            _atomic_write_text(path, json.dumps(payload, ensure_ascii=False,
                                                indent=2) + "\n")
            written.append(path)
        return written

    def asset_path(self, asset: PackAsset) -> Path:
        return self.asset_dir(asset.kind) / f"{asset.name}{asset.suffix}"

    def tag_path(self, tag: str) -> Path:
        key = str(tag or "").strip()
        namespace, _, name = key.partition(":")
        if not name:
            namespace, name = self.namespace, key
        folder = "function" if self.layout == LAYOUT_SINGULAR else "functions"
        return (self.root / "data" / namespace / "tags" / folder
                / f"{name}.json")

    def _asset_text(self, asset: PackAsset) -> str:
        if asset.suffix == ".mcfunction":
            text = asset.text or ""
            return text if text.endswith("\n") or not text else text + "\n"
        # JSON 资源：尽量格式化，解析不了就原样写（用户可能正在编辑）
        try:
            payload = json.loads(asset.text or "{}")
        except ValueError:
            return asset.text or "{}"
        return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"

    @classmethod
    def load(cls, root: str | Path,
             namespace: str | None = None) -> "AuthoringPack":
        """读取一个已有数据包（自动识别单数 / 复数目录）。"""
        root = Path(root)
        meta_path = root / "pack.mcmeta"
        description = "Generated by MCStudio"
        pack_format = PACK_FORMAT
        if meta_path.is_file():
            try:
                payload = json.loads(meta_path.read_text(encoding="utf-8"))
                pack = payload.get("pack", {}) if isinstance(payload, dict) \
                    else {}
                description = str(pack.get("description", description))
                pack_format = int(pack.get("pack_format", pack_format))
            except (ValueError, TypeError):              # pragma: no cover
                pass

        data_root = root / "data"
        namespaces: list[str] = []
        if data_root.is_dir():
            namespaces = sorted(item.name for item in data_root.iterdir()
                                if item.is_dir())
        # 自动挑命名空间：优先「有内容资源」的那个。
        # `minecraft` 这种只有 tags/ 的目录不该被当成包的主命名空间，
        # 所以给 tag 最低权重，资源类型各算 1 分。
        chosen = namespace
        if not chosen:
            best, best_score = "", 0
            for candidate in namespaces:
                score = 0
                for kind, (singular, plural, _suffix) in ASSET_KINDS.items():
                    weight = 0.1 if kind.startswith("tag") else 1
                    for folder in (singular, plural):
                        if (data_root / candidate / folder).is_dir():
                            score += weight
                if score > best_score or (score == best_score and score
                                          and candidate < best):
                    best, best_score = candidate, score
            chosen = best or (namespaces[0] if namespaces else "mcstudio")
        pack = cls(root=root, namespace=chosen, description=description,
                   pack_format=pack_format)

        # 目录布局：只要看到复数目录就认为它是复数布局
        plural_seen = False
        for kind, (singular, plural, suffix) in ASSET_KINDS.items():
            for folder, is_plural in ((singular, False), (plural, True)):
                directory = root / "data" / chosen / folder
                if not directory.is_dir():
                    continue
                if is_plural:
                    plural_seen = True
                for path in sorted(directory.rglob(f"*{suffix}")):
                    rel = path.relative_to(directory)
                    name = rel.with_suffix("").as_posix()
                    try:
                        text = path.read_text(encoding="utf-8")
                    except OSError:                     # pragma: no cover
                        text = ""
                    asset = PackAsset(kind=kind, name=name, text=text,
                                      namespace=chosen, path=path)
                    if not pack.find(kind, name):
                        pack.assets.append(asset)
        pack.layout = LAYOUT_PLURAL if plural_seen else LAYOUT_SINGULAR

        # 函数标签：本命名空间的全部 + minecraft 命名空间的 load/tick
        # （自己写的标签通常只关心这两类，别的包 / 别的命名空间不去动它）
        for namespace, folder in ((chosen, "tags/function"),
                                  (chosen, "tags/functions"),
                                  ("minecraft", "tags/function"),
                                  ("minecraft", "tags/functions")):
            directory = root / "data" / namespace / folder
            if not directory.is_dir():
                continue
            for path in sorted(directory.rglob("*.json")):
                rel = path.relative_to(directory).with_suffix("").as_posix()
                key = f"{namespace}:{rel}"
                try:
                    payload = json.loads(path.read_text(encoding="utf-8"))
                except (OSError, ValueError):           # pragma: no cover
                    continue
                values = payload.get("values") if isinstance(payload, dict) \
                    else None
                if isinstance(values, list):
                    pack.tags[key] = [
                        str(item.get("id", item)) if isinstance(item, dict)
                        else str(item) for item in values]
        return pack

    # ---- 便捷生成 ----

    def add_from_commands(self, name: str, commands: Iterable[str]) -> PackAsset:
        """把一批命令存成函数。"""
        lines = [str(cmd).strip() for cmd in commands if str(cmd).strip()]
        return self.add_asset("function", name, "\n".join(lines))

    def add_to_tag(self, tag: str, entry: str) -> None:
        key = tag if ":" in tag else f"{self.namespace}:{tag}"
        entries = self.tags.setdefault(key, [])
        target = entry if ":" in entry else f"{self.namespace}:{entry}"
        if target not in entries:
            entries.append(target)

    def auto_tag_load(self) -> None:
        """把所有函数挂进 `minecraft:load`（适合一次性初始化）。"""
        for asset in self.by_kind("function"):
            self.add_to_tag("minecraft:load",
                            f"{self.namespace}:{asset.name}")

    def auto_tag_tick(self, names: Iterable[str] | None = None) -> None:
        for asset in self.by_kind("function"):
            if names is not None and asset.name not in set(names):
                continue
            self.add_to_tag("minecraft:tick",
                            f"{self.namespace}:{asset.name}")

    def stats(self) -> dict[str, int]:
        functions = self.by_kind("function")
        return {
            "functions": len(functions),
            "commands": sum(asset.line_count() for asset in functions),
            "advancements": len(self.by_kind("advancement")),
            "loot_tables": len(self.by_kind("loot_table")),
            "predicates": len(self.by_kind("predicate")),
            "tags": len(self.tags),
            "namespaces": 1,
        }

    def validate(self) -> list[str]:
        """轻量自检：命名空间、函数名、JSON 语法、标签引用。"""
        problems: list[str] = []
        if not _NAMESPACE_RE.match(self.namespace or ""):
            problems.append(
                f"命名空间不合法（只允许小写字母 / 数字 / _ / - / .）："
                f"{self.namespace!r}")
        for asset in self.assets:
            if not asset.name:
                problems.append(f"{asset.kind} 有一个空名字")
            if asset.suffix == ".json" and asset.text.strip():
                try:
                    json.loads(asset.text)
                except ValueError as e:
                    problems.append(f"{asset.display} JSON 语法错误：{e}")
        known = {f"{self.namespace}:{asset.name}"
                 for asset in self.by_kind("function")}
        for tag, entries in self.tags.items():
            for entry in entries:
                if entry.startswith("#") or ":" not in entry:
                    continue
                namespace, _, name = entry.partition(":")
                if namespace == self.namespace and entry not in known:
                    problems.append(f"标签 {tag} 引用了不存在的函数 {entry}")
        return problems


