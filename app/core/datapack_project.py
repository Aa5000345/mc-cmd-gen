def advancement_template(title: str = "示例进度",
                         description: str = "说明",
                         trigger: str = "minecraft:tick") -> str:
    payload = {
        "display": {
            "icon": {"id": "minecraft:stone"},
            "title": {"text": title},
            "description": {"text": description},
            "frame": "task",
            "show_toast": True,
            "announce_to_chat": True,
        },
        "criteria": {"main": {"trigger": trigger}},
        "requirements": [["main"]],
    }
    return json.dumps(payload, ensure_ascii=False, indent=2)


def loot_table_template(item: str = "minecraft:diamond", count: int = 1,
                        rolls: int = 1) -> str:
    payload = {
        "type": "minecraft:generic",
        "pools": [{
            "rolls": max(1, int(rolls)),
            "entries": [{
                "type": "minecraft:item",
                "name": item,
                "functions": [{
                    "function": "minecraft:set_count",
                    "count": max(1, int(count)),
                }],
            }],
        }],
    }
    return json.dumps(payload, ensure_ascii=False, indent=2)


def predicate_template(entity: str = "minecraft:zombie") -> str:
    payload = {"condition": "minecraft:entity_properties",
               "entity": "this",
               "predicate": {"type": entity}}
    return json.dumps(payload, ensure_ascii=False, indent=2)


def function_template(kind: str = "main") -> str:
    templates = {
        "main": "# 主函数\nsay hello from MCStudio",
        "load": "# 加载时执行一次\ngamerule doDaylightCycle true",
        "tick": "# 每个游戏刻执行\n# 注意：tick 函数里不要放重活",
        "shop": "# 商店：购买钻石\nclear @s minecraft:diamond 10\ngive @s minecraft:diamond_sword 1",
        "kit": "# 发放装备\nclear @s\ngive @s minecraft:iron_helmet 1\ngive @s minecraft:iron_chestplate 1",
    }
    return templates.get(kind, templates["main"])


#: 数据包文件后缀 → 资源类型（导入时用）
def kind_from_suffix(path: str | Path) -> str | None:
    text = str(path).replace("\\", "/")
    if text.endswith(".mcfunction"):
        return "function"
    for kind, (singular, plural, suffix) in ASSET_KINDS.items():
        if suffix != ".json":
            continue
        if f"/{singular}/" in f"/{text}/" or f"/{plural}/" in f"/{text}/":
            return kind
    return None


def import_pack(source: str | Path, target: str | Path) -> "AuthoringPack":
    """把一个已有数据包复制到工作目录并读进来。"""
    source = Path(source)
    target = Path(target)
    if source.resolve() == target.resolve():            # pragma: no cover
        return AuthoringPack.load(target)
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(source, target)
    return AuthoringPack.load(target)


