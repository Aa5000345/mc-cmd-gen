def detect_version(command: str) -> str:
    """按命令里出现的语法特征推断它属于哪个版本。

    从新到旧逐级判断；无法判断时返回最旧的已知版本。
    """
    text = (command or "").strip()
    if not text:
        return KNOWN_VERSIONS[0]

    compact = text.replace(" ", "")

    # 1.21+：max_count 组件、custom_data、tool 组件
    if re.search(r"minecraft:(max_count|custom_data|tool|item_name)\b", compact):
        return "1.21"
    # 属性名已去 generic. 前缀 → 1.21
    if re.search(r"minecraft:(max_health|movement_speed|attack_damage|armor_toughness)\b",
                 compact) and "minecraft:generic." not in compact:
        return "1.21"
    # 1.20.6：组件里已经不再出现 generic.（与 1.21 同语法，保守判为 1.20.6）
    if "minecraft:generic." in compact and "[" in compact:
        return "1.20.6"
    # 1.20.5+：使用了组件方括号语法
    if re.search(r"\[(?:minecraft:)?[a-z_]+\s*=", text):
        return "1.20.5"
    # 老式物品 NBT / 老式分组语法
    if re.search(r"\b(Enchantments|display|AttributeModifiers|CustomModelData|"
                 r"CanDestroy|CanPlaceOn|HideFlags|RepairCost|SkullOwner|Potion)\s*:",
                 text):
        return "1.20.4"
    if re.search(r"\bCount\s*:|\bDamage\s*:", text):
        return "1.20.4"
    return KNOWN_VERSIONS[0]


def migrate_command(command: str) -> MigrationResult:
    text = command.strip()
    result = MigrationResult(original=command, migrated=text)
    result.detected = detect_version(text)
    if not text:
        return result

    if not is_older(result.detected, TARGET_VERSION):
        result.warnings.append(
            f"命令看起来已经是 {result.detected} 语法，无需迁移。")
        return result

    for rule in ALL_RULES:
        new_text, changed = rule.apply(result.migrated)
        if changed:
            result.migrated = new_text
            result.applied.append(f"{rule.description}（规则：{rule.name}）")

    if not result.applied:
        result.warnings.append("未命中任何迁移规则，命令保持原样。")

    _extra_warnings(text, result)
    return result


def _extra_warnings(text: str, result: MigrationResult) -> None:
    low = text.lower()
    if re.match(r"^/?tp\b", low):
        result.warnings.append("/tp 在 1.21.1 仍可用，但建议改用 /teleport。")
    compact = low.replace(" ", "")
    if "custom_name" not in compact and "display:{name" in compact:
        result.warnings.append("display.Name 已迁移为 minecraft:custom_name 组件。")
    if re.search(r"\{[^}]*Enchantments", text):
        result.warnings.append(
            "Enchantments NBT 已迁移为 minecraft:enchantments 组件，"
            "注意书类物品应用 stored_enchantments。")
    if re.search(r"\b(HandItems|ArmorItems|Inventory)\s*:", text):
        result.warnings.append(
            "HandItems/ArmorItems 在 1.20.5+ 已由 equipment 组件取代；"
            "方块的容器请改用 Items 的小写 slot 字段。")
    if re.search(r"minecraft:generic\.", text):
        result.warnings.append("属性名 generic. 前缀已按 1.21 规则去除。")
    if "#" in text and re.search(r"\bCount\s*:", text):
        result.warnings.append("物品结构的 Count/Slot 已改为小写 count/slot。")


