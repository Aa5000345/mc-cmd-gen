_NS_RE = re.compile(r"^[a-z0-9_.\-]+$")


def _validate_namespace(ns: str) -> str:
    ns = (ns or "").strip().lower() or "mccmdgen"
    if not _NS_RE.match(ns):
        ns = re.sub(r"[^a-z0-9_.\-]", "_", ns) or "mccmdgen"
    return ns


def validate_namespace(ns: str) -> str:
    return _validate_namespace(ns)


def _strip_slash(cmd: str) -> str:
    s = cmd.strip()
    return s[1:] if s.startswith("/") else s


def _write_pack_mcmeta(path: Path, description: str = _DEFAULT_DESC) -> None:
    path.mkdir(parents=True, exist_ok=True)
    (path / "pack.mcmeta").write_text(
        json.dumps({"pack": {"pack_format": PACK_FORMAT, "description": description}},
                   ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


def export_mcfunction(path: Path, commands: list[str],
                      namespace: str = "mccmdgen", name: str = "main",
                      description: str = _DEFAULT_DESC, header: str = "") -> Path:
    ns = _validate_namespace(namespace)
    name = (name or "main").strip() or "main"
    root = Path(path)
    func_dir = root / "data" / ns / "functions"
    func_dir.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    if header.strip():
        for line in header.splitlines():
            lines.append(f"# {line}")
    for cmd in commands:
        s = _strip_slash(cmd)
        if s:
            lines.append(s)

    func_file = func_dir / f"{name}.mcfunction"
    func_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
    _write_pack_mcmeta(root, description)
    return func_file


def export_mcfunction_multi(path: Path, functions: dict[str, list[str]],
                            namespace: str = "mccmdgen",
                            description: str = _DEFAULT_DESC) -> list[Path]:
    ns = _validate_namespace(namespace)
    root = Path(path)
    func_dir = root / "data" / ns / "functions"
    func_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name, cmds in (functions or {}).items():
        safe_name = (name or "main").strip() or "main"
        sub = func_dir / safe_name
        sub.parent.mkdir(parents=True, exist_ok=True)
        lines = [_strip_slash(c) for c in (cmds or []) if _strip_slash(c)]
        sub = sub.with_suffix(".mcfunction")
        sub.write_text("\n".join(lines) + "\n", encoding="utf-8")
        written.append(sub)
    _write_pack_mcmeta(root, description)
    return written


