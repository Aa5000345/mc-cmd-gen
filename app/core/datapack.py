def _attr_get(key: str | None) -> str | None:
    return _ATTR_RENAMES.get(key) if key else None


def _fix_attrs(text: str) -> str:
    """把文本里所有 generic. 属性名替换为 1.21 名称。"""
    for old, new in _ATTR_RENAMES.items():
        text = text.replace(old, new)
    return text


def _looks_like_nbt(text: str) -> bool:
    return text.startswith("{") and text.rstrip().endswith("}")


def _split_top_level(body: str) -> list[str]:
    parts: list[str] = []
    buf: list[str] = []
    depth = 0
    quote: str | None = None
    for ch in body:
        if quote:
            buf.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in ('"', "'"):
            quote = ch
            buf.append(ch)
            continue
        if ch in "{[(":
            depth += 1
        elif ch in "}])":
            depth = max(0, depth - 1)
        if ch == "," and depth == 0:
            parts.append("".join(buf))
            buf = []
            continue
        buf.append(ch)
    if buf:
        parts.append("".join(buf))
    return parts


def _nbt_pair_to_component(pair: str) -> str | None:
    if ":" not in pair:
        return None
    key, value = pair.split(":", 1)
    key = key.strip().strip('"')
    value = value.strip()

    if key == "display" and value.startswith("{") and value.endswith("}"):
        inner = value[1:-1]
        comps: list[str] = []
        for sub in _split_top_level(inner):
            if ":" not in sub:
                continue
            sk, sv = sub.split(":", 1)
            sk, sv = sk.strip(), sv.strip()
            if sk == "Name":
                comps.append(f"minecraft:custom_name={sv}")
            elif sk == "Lore":
                comps.append(f"minecraft:lore={sv}")
        return ",".join(comps) if comps else None

    comp = _NBT_TO_COMPONENT.get(key)
    if comp is None:
        return None

    if key == "Enchantments" and value.startswith("[") and value.endswith("]"):
        levels: list[str] = []
        for e in _split_top_level(value[1:-1]):
            e = e.strip()
            if not (e.startswith("{") and e.endswith("}")):
                continue
            em = re.search(r'id\s*:\s*"([^"]+)"', e)
            lm = re.search(r"lvl\s*:\s*(\d+)", e)
            if em and lm:
                levels.append(f'"{em.group(1)}":{lm.group(1)}')
        if levels:
            # 1.21 结构：minecraft:enchantments={levels:{"minecraft:sharpness":5}}
            return f"{comp}={{levels:{{{','.join(levels)}}}}}"
        return None

    if key == "AttributeModifiers" and value.startswith("[") and value.endswith("]"):
        out: list[str] = []
        for e in _split_top_level(value[1:-1]):
            e = e.strip()
            if not (e.startswith("{") and e.endswith("}")):
                continue
            e = re.sub(r"\bAttributeName\s*:", "type:", e)
            e = re.sub(r"\bName\s*:", "type:", e)
            e = re.sub(r"\bAmount\s*:", "amount:", e)
            e = re.sub(r"\bOperation\s*:", "operation:", e)
            e = re.sub(r"\bUUID\s*:", "id:", e)
            for old, new in _ATTR_RENAMES.items():
                e = e.replace(old, new)
            out.append(e)
        if out:
            return f"{comp}=[{','.join(out)}]"
        return None

    if key == "Potion" and value.startswith('"'):
        return f"{comp}={{potion:{value}}}"

    return f"{comp}={_fix_attrs(value)}"


def _balanced_braces(text: str) -> str | None:
    """取文本开头处的一对配对花括号（含引号保护）；不是以 { 开头则返回 None。"""
    if not text.startswith("{"):
        return None
    depth = 0
    quote = None
    for i, ch in enumerate(text):
        if quote:
            if ch == quote and text[i - 1] != "\\":
                quote = None
            continue
        if ch in ('"', "'"):
            quote = ch
            continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return text[:i + 1]
    return None


GIVE_NBT_RE = re.compile(
    r"^/?(?:give)\s+(?P<targets>\S+)\s+(?P<item>[^\s\[]+)"
    r"(?:\s+(?P<count>\d+))?"
    r"\s+(?P<nbt>\{.*\})\s*$",
    re.DOTALL,
)


def _upgrade_give(m: re.Match) -> str:
    """老式 /give <目标> <物品> [数量] {NBT} → 1.21.1 组件语法。"""
    target = m.group("targets")
    item = m.group("item")
    nbt_body = m.group("nbt")[1:-1]
    count = (m.group("count") or "").strip()

    components: list[str] = []
    unmapped: list[str] = []
    for pair in _split_top_level(nbt_body):
        if not pair.strip():
            continue
        comp = _nbt_pair_to_component(pair)
        if comp:
            components.append(comp)
        else:
            unmapped.append(pair.strip())

    # 无法映射的自定义 NBT 统一塞进 custom_data，避免静默丢数据
    if unmapped:
        components.append("minecraft:custom_data={" + ",".join(unmapped) + "}")

    if ":" not in item:
        item = f"minecraft:{item}"

    head = f"give {target} {item}"
    if components:
        head += "[" + ",".join(components) + "]"
    if count and count != "1":
        head += " " + count
    return head


def _upgrade_give_full(m: re.Match) -> str:
    """整条命令级替换（由 MigrationRule.full_match 触发）。"""
    return _upgrade_give(m)


