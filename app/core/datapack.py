@dataclass
class FunctionEntry:
    name: str
    commands: list[str] = field(default_factory=list)

    def to_text(self) -> str:
        return "\n".join(self.commands) + ("\n" if self.commands else "")


@dataclass
class DatapackProject:
    root: Path
    namespace: str = "mccmdgen"
    description: str = "Generated by MCCmdGen"
    functions: list[FunctionEntry] = field(default_factory=list)

    def pack_mcmeta_path(self) -> Path:
        return self.root / "pack.mcmeta"

    def functions_dir(self) -> Path:
        return self.root / "data" / self.namespace / "functions"

    def tags_dir(self) -> Path:
        return self.root / "data" / self.namespace / "tags"

    def predicates_dir(self) -> Path:
        return self.root / "data" / self.namespace / "predicates"

    def advancements_dir(self) -> Path:
        return self.root / "data" / self.namespace / "advancements"

    def loot_tables_dir(self) -> Path:
        return self.root / "data" / self.namespace / "loot_tables"

    def ensure_dirs(self) -> None:
        for d in (self.root, self.functions_dir(),
                  self.tags_dir() / "functions",
                  self.predicates_dir(), self.advancements_dir(),
                  self.loot_tables_dir()):
            d.mkdir(parents=True, exist_ok=True)

    def write_pack_mcmeta(self) -> Path:
        self.root.mkdir(parents=True, exist_ok=True)
        path = self.pack_mcmeta_path()
        path.write_text(
            json.dumps({"pack": {"pack_format": PACK_FORMAT,
                                 "description": self.description}},
                       ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        return path

    def save(self) -> list[Path]:
        self.ensure_dirs()
        self.write_pack_mcmeta()
        written: list[Path] = []
        for fn in self.functions:
            safe = _sanitize_function_name(fn.name)
            path = self.functions_dir() / f"{safe}.mcfunction"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(fn.to_text(), encoding="utf-8")
            written.append(path)
        return written

    def load_from_disk(self, root: Path | None = None) -> None:
        self.root = Path(root or self.root)
        meta = self.pack_mcmeta_path()
        if meta.exists():
            try:
                data = json.loads(meta.read_text(encoding="utf-8"))
                self.description = str(data.get("pack", {}).get("description", self.description))
            except Exception:
                pass
        self.functions = []
        fdir = self.functions_dir()
        if fdir.exists():
            for p in sorted(fdir.rglob("*.mcfunction")):
                rel = p.relative_to(fdir).with_suffix("")
                try:
                    text = p.read_text(encoding="utf-8")
                except Exception:
                    text = ""
                self.functions.append(
                    FunctionEntry(name=rel.as_posix(), commands=text.splitlines())
                )

    def add_function(self, name: str, commands: list[str] | None = None) -> FunctionEntry:
        name = _sanitize_function_name(name) or "main"
        for fn in self.functions:
            if fn.name == name:
                if commands:
                    fn.commands = list(commands)
                return fn
        fn = FunctionEntry(name=name, commands=list(commands or []))
        self.functions.append(fn)
        return fn

    def remove_function(self, name: str) -> None:
        self.functions = [f for f in self.functions if f.name != name]


_FN_RE = re.compile(r"[^a-z0-9_./\-]+")


def _sanitize_function_name(name: str) -> str:
    s = (name or "").strip().lower().replace(" ", "_")
    s = _FN_RE.sub("_", s)
    return s.strip("/")


