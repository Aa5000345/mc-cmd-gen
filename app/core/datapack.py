KNOWN_VERSIONS = ["1.20.4", "1.20.5", "1.20.6", "1.21", "1.21.1"]
TARGET_VERSION = "1.21.1"

# 版本比较用序号（越大越新）
_VERSION_ORDER = {v: i for i, v in enumerate(KNOWN_VERSIONS)}


def version_index(version: str) -> int:
    """把版本号映射为可比较的序号；未知版本按最旧处理。"""
    v = (version or "").strip()
    if v in _VERSION_ORDER:
        return _VERSION_ORDER[v]
    m = re.match(r"^1\.(\d+)(?:\.(\d+))?", v)
    if m:
        return max(0, int(m.group(1)) - 20)
    return 0


def is_older(version: str, than: str = TARGET_VERSION) -> bool:
    return version_index(version) < version_index(than)


@dataclass
class MigrationRule:
    name: str
    pattern: re.Pattern
    replacement: str | Callable[[re.Match], str]
    description: str
    full_match: bool = False

    def apply(self, text: str) -> tuple[str, bool]:
        """full_match 规则要求整条命令匹配，重新生成整条命令；
        其余规则做局部替换。"""
        if self.full_match:
            m = self.pattern.match(text.strip())
            if not m:
                return text, False
            replaced = self.replacement(m)
            return replaced, replaced != text
        new, n = self.pattern.subn(self.replacement, text)
        return new, n > 0


@dataclass
class MigrationResult:
    original: str
    migrated: str
    applied: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    detected: str = ""

    @property
    def changed(self) -> bool:
        return bool(self.applied)


