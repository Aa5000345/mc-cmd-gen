"""「数据包工程」页签：图形化编辑器。

三栏布局：

    左   资源树（函数 / 进度 / 战利品表 / 谓词 / 函数标签）+ 新建 / 删除
    中   编辑器（函数是命令文本，JSON 资源是带语法检查的 JSON 文本）
    右   预览与自检（命令条数、JSON 结构、标签引用、落盘结果）

落盘走 `app.core.datapack_project`，原子替换；工程目录默认放在
应用数据目录的 `user_data/datapacks/<命名空间>/`，
也可以直接指向存档的 `datapacks/` 目录（这样游戏立刻能看到）。
"""
