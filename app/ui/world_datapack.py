    # 工程生命周期
    # ==================================================================
    def current_pack(self) -> AuthoringPack | None:
        return getattr(self, "_pack", None)

    def _set_pack(self, pack: AuthoringPack) -> None:
        self._pack = pack
        self.pack_namespace.setText(pack.namespace)
        self.pack_description.setText(pack.description)
        self.pack_format.setValue(int(pack.pack_format))
        self._refresh_pack_tree()
        self._refresh_pack_info()
        self.pack_status.setText(f"工程目录：{pack.root}")

    def _on_pack_new(self) -> None:
        name, ok = QInputDialog.getText(
            self, "新建数据包工程", "命名空间（小写字母 / 数字 / 下划线）：",
            text=self.pack_namespace.text().strip() or "mcstudio")
        if not ok or not name.strip():
            return
        namespace = name.strip().lower()
        pack = AuthoringPack(root=packs_root() / namespace,
                             namespace=namespace,
                             description="Generated by MCStudio")
        pack.add_from_commands("main", function_template("main").splitlines())
        pack.add_from_commands("load", function_template("load").splitlines())
        pack.auto_tag_load()
        self._set_pack(pack)
        self.statusMessage.emit(f"已新建数据包工程：{pack.root}")

    def _on_pack_open(self) -> None:
        path = QFileDialog.getExistingDirectory(
            self, "选择数据包目录（含 pack.mcmeta）", str(packs_root()))
        if not path:
            return
        try:
            pack = AuthoringPack.load(path)
        except Exception as e:
            QMessageBox.warning(self, "读取失败", str(e))
            return
        self._set_pack(pack)
        self.statusMessage.emit(f"已打开数据包：{pack.summary()}")

    def _on_pack_from_world(self) -> None:
        world = self.world()
        if world is None or not world.is_open():
            QMessageBox.information(self, "提示", "请先打开一个世界存档。")
            return
        folder = world.path / "datapacks"
        if not folder.is_dir():
            QMessageBox.information(self, "提示",
                                    "这个存档没有 datapacks/ 目录。")
            return
        candidates = sorted(item for item in folder.iterdir() if item.is_dir())
        if not candidates:
            QMessageBox.information(self, "提示", "datapacks/ 下没有目录型数据包。")
            return
        names = [item.name for item in candidates]
        choice, ok = QInputDialog.getItem(
            self, "从存档导入数据包", "选择要编辑的数据包：", names, 0, False)
        if not ok:
            return
        source = folder / choice
        target = packs_root() / f"{choice}-copy"
        try:
            pack = import_pack(source, target)
        except Exception as e:
            QMessageBox.warning(self, "导入失败", str(e))
            return
        self._set_pack(pack)
        self.statusMessage.emit(
            f"已把存档里的「{choice}」导入到 {pack.root}")

    def _on_pack_save(self) -> None:
        pack = self.current_pack()
        if pack is None:
            self.statusMessage.emit("还没有工程，先新建或打开一个。")
            return
        self._sync_pack_fields()
        self._commit_pack_editor()
        problems = pack.validate()
        if problems:
            answer = QMessageBox.warning(
                self, "自检有问题",
                "\n".join(problems[:12])
                + "\n\n仍然保存吗？",
                QMessageBox.StandardButton.Save
                | QMessageBox.StandardButton.Cancel,
                QMessageBox.StandardButton.Cancel)
            if answer != QMessageBox.StandardButton.Save:
                return
        try:
            written = pack.save()
        except Exception as e:
            QMessageBox.warning(self, "保存失败", str(e))
            return
        self._refresh_pack_tree()
        self._refresh_pack_info()
        self.pack_report.setPlainText(
            f"■ 已写入 {len(written)} 个文件：\n"
            + "\n".join(f"    {path}" for path in written[:40]))
        self.statusMessage.emit(f"数据包已保存（{len(written)} 个文件）。")

    def _on_pack_save_to(self) -> None:
        pack = self.current_pack()
        if pack is None:
            self.statusMessage.emit("还没有工程。")
            return
        self._sync_pack_fields()
        self._commit_pack_editor()
        path = QFileDialog.getExistingDirectory(
            self, "另存到目录", str(packs_root()))
        if not path:
            return
        target = Path(path)
        if (target / "data").exists() or (target / "pack.mcmeta").exists():
            answer = QMessageBox.question(
                self, "目录里已有数据包",
                f"{target} 里已经有 data/ 或 pack.mcmeta，"
                "继续会覆盖同名文件。继续？",
                QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
                QMessageBox.StandardButton.No)
            if answer != QMessageBox.StandardButton.Yes:
                return
        pack.root = target
        try:
            written = pack.save()
        except Exception as e:
            QMessageBox.warning(self, "保存失败", str(e))
            return
        self.pack_status.setText(f"工程目录：{pack.root}")
        self.pack_report.setPlainText(
            f"■ 已导出 {len(written)} 个文件到 {target}")
        self.statusMessage.emit(f"已导出数据包到 {target}")

    # ---- 树 ----

    def _refresh_pack_tree(self) -> None:
        tree = getattr(self, "pack_tree", None)
        if tree is None:                                # pragma: no cover
            return
        tree.clear()
        pack = self.current_pack()
        if pack is None:
            return
        groups = (
            ("function", "函数"),
            ("advancement", "进度"),
            ("loot_table", "战利品表"),
            ("predicate", "谓词"),
        )
        for kind, label in groups:
            assets = pack.by_kind(kind)
            node = QTreeWidgetItem([f"{label}（{len(assets)}）"])
            node.setData(0, Qt.ItemDataRole.UserRole, ("group", kind))
            tree.addTopLevelItem(node)
            for asset in assets:
                item = QTreeWidgetItem([f"{asset.name}{asset.suffix}"])
                item.setData(0, Qt.ItemDataRole.UserRole, ("asset", kind,
                                                           asset.name))
                item.setToolTip(0, f"{asset.summary()}\n"
                                   f"{pack.asset_path(asset)}")
                node.addChild(item)
            node.setExpanded(bool(assets))
        tag_node = QTreeWidgetItem([f"函数标签（{len(pack.tags)}）"])
        tag_node.setData(0, Qt.ItemDataRole.UserRole, ("group", "tag"))
        tree.addTopLevelItem(tag_node)
        for tag, entries in sorted(pack.tags.items()):
            item = QTreeWidgetItem([f"{tag}（{len(entries)}）"])
            item.setData(0, Qt.ItemDataRole.UserRole, ("tag", tag))
            item.setToolTip(0, "\n".join(entries))
            tag_node.addChild(item)
        tag_node.setExpanded(True)

    def _selected_pack_asset(self):
        tree = self.pack_tree
        item = tree.currentItem()
        if item is None:
            return None
        data = item.data(0, Qt.ItemDataRole.UserRole)
        if not data or data[0] != "asset":
            return None
        pack = self.current_pack()
        if pack is None:
            return None
        return pack.find(data[1], data[2])

    def _on_pack_item_activated(self, item: QTreeWidgetItem, _column: int) -> None:
        data = item.data(0, Qt.ItemDataRole.UserRole) if item else None
        if not data:
            return
        if data[0] == "asset":
            pack = self.current_pack()
            asset = pack.find(data[1], data[2]) if pack else None
            if asset is None:
                return
            self._commit_pack_editor()
            self._load_pack_asset(asset)
        elif data[0] == "tag":
            self.pack_report.setPlainText(
                f"■ {data[1]}\n"
                + "\n".join(f"    {entry}"
                            for entry in self.current_pack().tag_entries(
                                data[1])))
        elif data[0] == "group":
            self.pack_report.setPlainText(
                f"■ {self.current_pack().summary()}\n\n"
                + "\n".join(f"    {asset.display} — {asset.summary()}"
                            for asset in self.current_pack().assets))

    def _load_pack_asset(self, asset) -> None:
        self._current_asset = (asset.kind, asset.name)
        self.pack_asset_label.setText(
            f"{asset.kind} · {asset.name}{asset.suffix}")
        self.pack_editor.blockSignals(True)
        self.pack_editor.setPlainText(asset.text)
        self.pack_editor.blockSignals(False)
        self._refresh_pack_info()
        self._preview_pack_asset(asset)

    def _commit_pack_editor(self) -> None:
        pack = self.current_pack()
        current = getattr(self, "_current_asset", None)
        if pack is None or current is None:
            return
        asset = pack.find(*current)
        if asset is None:                               # pragma: no cover
            return
        text = self.pack_editor.toPlainText()
        if text != asset.text:
            asset.text = text
            asset.dirty = True

    def _on_pack_text_changed(self) -> None:
        pack = self.current_pack()
        current = getattr(self, "_current_asset", None)
        if pack is None or current is None:
            return
        asset = pack.find(*current)
        if asset is None:
            return
        asset.text = self.pack_editor.toPlainText()
        asset.dirty = True
        self._preview_pack_asset(asset)

    def _preview_pack_asset(self, asset) -> None:
        lines = [f"■ {asset.display}", f"    {asset.summary()}"]
        if asset.kind == "function":
            commands = asset.commands()
            lines.append(f"    命令 {len(commands)} 条")
            for command in commands[:40]:
                lines.append(f"      {command}")
            if len(commands) > 40:
                lines.append(f"      … 另有 {len(commands) - 40} 条")
        elif asset.suffix == ".json":
            try:
                import json
                payload = json.loads(asset.text or "{}")
                lines.append("    JSON 语法：通过")
                lines.append("    顶层字段：" + "、".join(sorted(payload)))
            except ValueError as e:
                lines.append(f"    JSON 语法错误：{e}")
        self.pack_report.setPlainText("\n".join(lines))

    # ---- 资源操作 ----

    def _on_pack_add(self) -> None:
        pack = self.current_pack()
        if pack is None:
            QMessageBox.information(self, "提示", "请先新建或打开一个工程。")
            return
        kind = str(self.pack_new_kind.currentData())
        name, ok = QInputDialog.getText(
            self, "新建资源", f"{kind} 名字（可带子目录，例如 shop/buy）：",
            text="new_" + kind.split("/")[-1])
        if not ok or not name.strip():
            return
        text = ""
        if kind == "function":
            text = function_template("main")
        elif kind == "advancement":
            text = advancement_template(name.strip())
        elif kind == "loot_table":
            text = loot_table_template()
        elif kind == "predicate":
            text = predicate_template()
        asset = pack.add_asset(kind, name, text)
        self._refresh_pack_tree()
        self._load_pack_asset(asset)
        self.statusMessage.emit(f"已新建 {asset.display}")

    def _on_pack_remove(self) -> None:
        asset = self._selected_pack_asset()
        pack = self.current_pack()
        if asset is None or pack is None:
            self.statusMessage.emit("请先在左边选中一个资源。")
            return
        answer = QMessageBox.question(
            self, "删除资源", f"删除 {asset.display}？（保存后磁盘上的文件也会删掉）",
            QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
            QMessageBox.StandardButton.No)
        if answer != QMessageBox.StandardButton.Yes:
            return
        pack.remove_asset(asset.kind, asset.name)
        self._current_asset = None
        self.pack_editor.clear()
        self.pack_asset_label.setText("（没有选中资源）")
        self._refresh_pack_tree()
        self._refresh_pack_info()

    def _on_pack_tag(self, tag: str) -> None:
        asset = self._selected_pack_asset()
        pack = self.current_pack()
        if pack is None:
            return
        if asset is None or asset.kind != "function":
            self.statusMessage.emit("请先在左边选中一个函数。")
            return
        pack.add_to_tag(tag, f"{pack.namespace}:{asset.name}")
        self._refresh_pack_tree()
        self._refresh_pack_info()
        self.statusMessage.emit(f"已把 {asset.name} 挂进 {tag} 标签。")

    def _on_pack_validate(self) -> None:
        pack = self.current_pack()
        if pack is None:
            return
        self._sync_pack_fields()
        self._commit_pack_editor()
        problems = pack.validate()
        stats = pack.stats()
        lines = [f"■ {pack.summary()}", ""]
        lines.append("■ 统计：" + "、".join(
            f"{key} {value}" for key, value in stats.items()))
        lines.append("")
        if problems:
            lines.append(f"■ 自检发现 {len(problems)} 个问题：")
            lines.extend(f"    {item}" for item in problems[:40])
        else:
            lines.append("■ 自检通过：没有发现问题。")
        self.pack_report.setPlainText("\n".join(lines))
        self.statusMessage.emit(
            f"自检完成：{'通过' if not problems else str(len(problems)) + ' 个问题'}")

    def _on_pack_tree_menu(self, position) -> None:
        item = self.pack_tree.itemAt(position)
        menu = QMenu(self.pack_tree)
        act_add = menu.addAction("新建资源…")
        act_add.triggered.connect(self._on_pack_add)
        data = item.data(0, Qt.ItemDataRole.UserRole) if item else None
        if data and data[0] == "asset":
            act_copy = menu.addAction("复制名字")
            act_copy.triggered.connect(
                lambda: QGuiApplication.clipboard().setText(
                    f"{self.current_pack().namespace}:{data[2]}"))
            act_del = menu.addAction("删除资源")
            act_del.triggered.connect(self._on_pack_remove)
        if data and data[0] == "tag":
            act_show = menu.addAction("查看标签内容")
            act_show.triggered.connect(
                lambda: self._on_pack_item_activated(item, 0))
        menu.exec(self.pack_tree.viewport().mapToGlobal(position))

    # ---- 编辑辅助 ----

    def _insert_pack_template(self, key: str) -> None:
        self.pack_editor.insertPlainText(function_template(key) + "\n")

    def _insert_pack_json(self, builder) -> None:
        try:
            text = builder()
        except TypeError:                               # pragma: no cover
            text = builder("示例")
        self.pack_editor.setPlainText(text)

    def _on_pack_find(self) -> None:
        text, ok = QInputDialog.getText(self, "在函数里查找", "关键字：")
        if not ok or not text:
            return
        cursor = self.pack_editor.textCursor()
        if self.pack_editor.find(text):
            self.statusMessage.emit(f"找到「{text}」")
        else:
            self.pack_editor.setTextCursor(cursor)
            self.statusMessage.emit(f"没有找到「{text}」")

    def _on_pack_to_output(self) -> None:
        asset = self._selected_pack_asset()
        if asset is None or asset.kind != "function":
            self.statusMessage.emit("请先选中一个函数。")
            return
        commands = asset.commands()
        if not commands:
            self.statusMessage.emit("这个函数里还没有命令。")
            return
        self.commandsReady.emit("\n".join(commands))
        self.statusMessage.emit(f"已把 {len(commands)} 条命令送到输出区。")

    def _on_pack_from_output(self) -> None:
        asset = self._selected_pack_asset()
        if asset is None:
            self.statusMessage.emit("请先选中一个资源。")
            return
        text = getattr(self, "_output_text", "") or ""
        if not text.strip():
            self.statusMessage.emit("没有可写入的内容（从输出区取不到）。")
            return
        self.pack_editor.setPlainText(text)
        self.statusMessage.emit(f"已把输出区内容写进 {asset.display}")

    # ---- 概览 ----

    def _sync_pack_fields(self) -> None:
        pack = self.current_pack()
        if pack is None:
            return
        namespace = self.pack_namespace.text().strip().lower() or pack.namespace
        pack.namespace = namespace
        pack.description = self.pack_description.text().strip() \
            or pack.description
        pack.pack_format = int(self.pack_format.value())

    def _refresh_pack_info(self) -> None:
        pack = self.current_pack()
        if pack is None or not hasattr(self, "pack_info"):
            return
        self.pack_info.setText(
            f"{pack.summary()}\n目录：{pack.root}")
        stats = pack.stats()
        self.pack_stats.setText(
            "、".join(f"{key} {value}" for key, value in stats.items())
            + f" · 布局：{'1.21 单数' if pack.layout == 'singular' else '1.20 复数'}")
        if hasattr(self, "pack_status"):
            self.pack_status.setText(f"工程目录：{pack.root}")


