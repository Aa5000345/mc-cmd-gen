def packs_root() -> Path:
    """默认的数据包工程目录。"""
    path = user_data_dir() / "datapacks"
    path.mkdir(parents=True, exist_ok=True)
    return path


class DatapackTabMixin:
    """「数据包工程」页签。"""

    def _build_datapack_project_tab(self) -> QWidget:
        page = QWidget()
        outer = QVBoxLayout(page)
        outer.setContentsMargins(*MARGINS["page"])
        outer.setSpacing(SPACING["sm"])

        outer.addWidget(self._build_pack_header())

        split = QSplitter(Qt.Orientation.Horizontal)
        tree = self._build_pack_tree()
        editor = self._build_pack_editor()
        preview = self._build_pack_preview()
        # 中栏最窄只有 420px：两侧给「能收起」的最小宽度 + 拉伸比例，
        # 而不是写死 260/620/320 的像素（那样两侧会被裁掉）
        for widget, minimum in ((tree, 150), (editor, 240), (preview, 140)):
            widget.setMinimumWidth(minimum)
            split.addWidget(widget)
        split.setChildrenCollapsible(True)
        split.setStretchFactor(0, 1)
        split.setStretchFactor(1, 3)
        split.setStretchFactor(2, 1)
        split.setSizes([220, 520, 220])
        outer.addWidget(split, 1)
        return page

